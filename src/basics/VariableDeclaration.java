package basics;

public class VariableDeclaration {
    public static void main(String[] args){
        String name;
        int num = 1;
        System.out.println("Num initial value : "+num);
        name = "Siddharth";
        num = 5;

        System.out.println("Name : "+name);
        System.out.println("Num final value : "+num);

    }
}
